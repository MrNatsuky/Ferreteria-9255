CREATE OR REPLACE PROCEDURE PRC_REGISTRAR_BITACORA_9255 (
    P_TABLA       IN VARCHAR2,
    P_ACCION      IN VARCHAR2,
    P_ID_REGISTRO IN NUMBER,
    P_USUARIO     IN VARCHAR2,
    P_DETALLE     IN VARCHAR2
) IS
BEGIN
    INSERT INTO BITACORA_9255 (TABLA_AFECTADA, ACCION, ID_REGISTRO, USUARIO, DETALLE)
    VALUES (P_TABLA, P_ACCION, P_ID_REGISTRO, NVL(P_USUARIO, USER), P_DETALLE);
END;
/

CREATE OR REPLACE PROCEDURE PRC_REGISTRAR_ABONO_9255 (
    P_ID_CUENTA_COBRAR IN NUMBER,
    P_ID_FORMA_PAGO    IN NUMBER,
    P_MONTO            IN NUMBER,
    P_REFERENCIA       IN VARCHAR2,
    P_BANCO            IN VARCHAR2,
    P_FECHA            IN DATE,
    P_USUARIO          IN VARCHAR2
) IS
    V_SALDO NUMBER(12,2);
BEGIN
    SELECT SALDO
      INTO V_SALDO
      FROM CUENTA_POR_COBRAR_9255
     WHERE ID_CUENTA_COBRAR = P_ID_CUENTA_COBRAR;

    IF P_MONTO > V_SALDO THEN
        RAISE_APPLICATION_ERROR(-20101, 'El abono es mayor que el saldo pendiente (' || V_SALDO || ').');
    END IF;

    INSERT INTO ABONO_CLIENTE_9255 (ID_CUENTA_COBRAR, ID_FORMA_PAGO, FECHA_ABONO, MONTO, NUMERO_REFERENCIA, BANCO, CREADO_POR)
    VALUES (P_ID_CUENTA_COBRAR, P_ID_FORMA_PAGO, P_FECHA, P_MONTO, P_REFERENCIA, P_BANCO, P_USUARIO);

    UPDATE CUENTA_POR_COBRAR_9255
       SET SALDO = SALDO - P_MONTO,
           MODIFICADO_POR = P_USUARIO
     WHERE ID_CUENTA_COBRAR = P_ID_CUENTA_COBRAR;

    IF V_SALDO - P_MONTO = 0 THEN
        UPDATE CUENTA_POR_COBRAR_9255
           SET ESTADO = 'PAGADA',
               MODIFICADO_POR = P_USUARIO
         WHERE ID_CUENTA_COBRAR = P_ID_CUENTA_COBRAR;
    END IF;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20102, 'No existe la cuenta por cobrar ' || P_ID_CUENTA_COBRAR);
END;
