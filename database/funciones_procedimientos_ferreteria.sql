CREATE OR REPLACE FUNCTION FN_SALDO_CLIENTE_9255 (P_ID_CLIENTE IN NUMBER) RETURN NUMBER IS
    V_SALDO NUMBER(12,2);
BEGIN
    SELECT NVL(SUM(SALDO), 0)
      INTO V_SALDO
      FROM CUENTA_POR_COBRAR_9255
     WHERE ID_CLIENTE = P_ID_CLIENTE
       AND ESTADO = 'PENDIENTE';
    RETURN V_SALDO;
END;
