      FROM FACTURA_9255
     WHERE ID_FACTURA = :NEW.ID_FACTURA;

    SELECT PRECIO_COSTO INTO V_COSTO FROM PRODUCTO_9255 WHERE ID_PRODUCTO = :NEW.ID_PRODUCTO;

    PRC_REGISTRA_MOV_INVENTARIO_9255('SALIDA_VENTA', V_SUCURSAL, :NEW.ID_PRODUCTO, :NEW.CANTIDAD, V_COSTO,
                                     V_EMPLEADO, 'FACTURA ' || V_SERIE || '-' || V_NUMERO, V_FECHA);

    UPDATE FACTURA_9255
       SET SUBTOTAL = SUBTOTAL + :NEW.SUBTOTAL,
           IMPUESTO = ROUND((SUBTOTAL + :NEW.SUBTOTAL) * PORCENTAJE_IMPUESTO / 100, 2),
           TOTAL    = (SUBTOTAL + :NEW.SUBTOTAL) + ROUND((SUBTOTAL + :NEW.SUBTOTAL) * PORCENTAJE_IMPUESTO / 100, 2)
     WHERE ID_FACTURA = :NEW.ID_FACTURA;
END;
