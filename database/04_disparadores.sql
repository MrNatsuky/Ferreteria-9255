-- Toda baja debe indicar el motivo (RN-08)
CREATE OR REPLACE TRIGGER TRG_BIR_MOVIMIENTO_INVENTARIO_9255
BEFORE INSERT ON MOVIMIENTO_INVENTARIO_9255
FOR EACH ROW
DECLARE
    V_CODIGO VARCHAR2(20);
BEGIN
    SELECT CODIGO INTO V_CODIGO
      FROM TIPO_MOVIMIENTO_9255
     WHERE ID_TIPO_MOVIMIENTO = :NEW.ID_TIPO_MOVIMIENTO;

    IF V_CODIGO = 'BAJA' AND :NEW.ID_MOTIVO_BAJA IS NULL THEN
        RAISE_APPLICATION_ERROR(-20200, 'Toda baja de inventario debe indicar el motivo.');
    END IF;
END;
/

-- Actualiza la existencia de la bodega con cada movimiento (RN-03).
-- Si la operacion del tipo es '+' suma; si es '-' resta, y no permite quedar en negativo.
CREATE OR REPLACE TRIGGER TRG_AIR_MOVIMIENTO_INVENTARIO_9255
AFTER INSERT ON MOVIMIENTO_INVENTARIO_9255
FOR EACH ROW
DECLARE
    V_OPERACION CHAR(1);
    V_EXISTENCIA NUMBER(12,2);
BEGIN
    SELECT OPERACION INTO V_OPERACION
      FROM TIPO_MOVIMIENTO_9255
     WHERE ID_TIPO_MOVIMIENTO = :NEW.ID_TIPO_MOVIMIENTO;

    V_EXISTENCIA := FN_EXISTENCIA_9255(:NEW.ID_BODEGA, :NEW.ID_PRODUCTO);

    IF V_OPERACION = '-' THEN
        IF V_EXISTENCIA < :NEW.CANTIDAD THEN
            RAISE_APPLICATION_ERROR(-20201, 'No hay existencia suficiente del producto ' || :NEW.ID_PRODUCTO
                                    || ' en la bodega ' || :NEW.ID_BODEGA || '. Disponible: ' || V_EXISTENCIA);
        END IF;
        UPDATE INVENTARIO_9255
           SET EXISTENCIA = EXISTENCIA - :NEW.CANTIDAD,
               FECHA_ULTIMO_MOVIMIENTO = :NEW.FECHA_MOVIMIENTO
         WHERE ID_BODEGA = :NEW.ID_BODEGA
           AND ID_PRODUCTO = :NEW.ID_PRODUCTO;
    ELSE
        UPDATE INVENTARIO_9255
           SET EXISTENCIA = EXISTENCIA + :NEW.CANTIDAD,
               FECHA_ULTIMO_MOVIMIENTO = :NEW.FECHA_MOVIMIENTO
         WHERE ID_BODEGA = :NEW.ID_BODEGA
           AND ID_PRODUCTO = :NEW.ID_PRODUCTO;
        -- Si el producto nunca habia estado en esa bodega, se crea su registro
        IF SQL%ROWCOUNT = 0 THEN
            INSERT INTO INVENTARIO_9255 (ID_BODEGA, ID_PRODUCTO, EXISTENCIA, FECHA_ULTIMO_MOVIMIENTO)
            VALUES (:NEW.ID_BODEGA, :NEW.ID_PRODUCTO, :NEW.CANTIDAD, :NEW.FECHA_MOVIMIENTO);
        END IF;
    END IF;
END;
/

