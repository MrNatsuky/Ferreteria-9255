-- RN-07: un abono no puede ser mayor al saldo; descuenta el saldo y, si llega a cero,
-- la cuenta queda PAGADA
CREATE OR REPLACE TRIGGER TRG_BIR_ABONO_CLIENTE_9255
BEFORE INSERT ON ABONO_CLIENTE_9255
FOR EACH ROW
DECLARE
    V_SALDO    NUMBER(12,2);
    V_REQUIERE CHAR(1);
BEGIN
    SELECT REQUIERE_REFERENCIA INTO V_REQUIERE FROM FORMA_PAGO_9255 WHERE ID_FORMA_PAGO = :NEW.ID_FORMA_PAGO;
    IF V_REQUIERE = 'S' AND :NEW.NUMERO_REFERENCIA IS NULL THEN
        RAISE_APPLICATION_ERROR(-20222, 'Esta forma de pago requiere numero de referencia.');
    END IF;

    SELECT SALDO INTO V_SALDO FROM CUENTA_POR_COBRAR_9255 WHERE ID_CUENTA_COBRAR = :NEW.ID_CUENTA_COBRAR;
    IF :NEW.MONTO > V_SALDO THEN
        RAISE_APPLICATION_ERROR(-20223, 'El abono es mayor que el saldo pendiente (' || V_SALDO || ').');
    END IF;

    UPDATE CUENTA_POR_COBRAR_9255
       SET SALDO = SALDO - :NEW.MONTO
     WHERE ID_CUENTA_COBRAR = :NEW.ID_CUENTA_COBRAR;

    IF V_SALDO - :NEW.MONTO = 0 THEN
        UPDATE CUENTA_POR_COBRAR_9255 SET ESTADO = 'PAGADA' WHERE ID_CUENTA_COBRAR = :NEW.ID_CUENTA_COBRAR;
    END IF;
END;
/


