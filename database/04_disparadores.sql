     WHERE B.ID_BODEGA = :NEW.ID_BODEGA_DESTINO;

    :NEW.ESTADO   := 'PENDIENTE';
    :NEW.SUBTOTAL := 0;
    :NEW.IMPUESTO := 0;
    :NEW.TOTAL    := 0;
END;
/

