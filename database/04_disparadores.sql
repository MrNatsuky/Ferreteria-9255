-- Al crear la compra: impuesto y tipo de cambio del pais de la bodega destino
CREATE OR REPLACE TRIGGER TRG_BIR_COMPRA_9255
BEFORE INSERT ON COMPRA_9255
FOR EACH ROW
BEGIN
    SELECT P.PORCENTAJE_IMPUESTO, P.TIPO_CAMBIO_QUETZAL
      INTO :NEW.PORCENTAJE_IMPUESTO, :NEW.TIPO_CAMBIO_QUETZAL
      FROM BODEGA_9255 B
      JOIN SUCURSAL_9255 S ON S.ID_SUCURSAL = B.ID_SUCURSAL
      JOIN REGION_9255 R   ON R.ID_REGION = S.ID_REGION
