      JOIN REGION_9255 R ON R.ID_REGION = S.ID_REGION
      JOIN PAIS_9255 P   ON P.ID_PAIS = R.ID_PAIS
     WHERE S.ID_SUCURSAL = :NEW.ID_SUCURSAL;

    UPDATE SUCURSAL_9255
       SET CORRELATIVO_FACTURA = CORRELATIVO_FACTURA + 1
     WHERE ID_SUCURSAL = :NEW.ID_SUCURSAL;
    SELECT CORRELATIVO_FACTURA INTO :NEW.NUMERO FROM SUCURSAL_9255 WHERE ID_SUCURSAL = :NEW.ID_SUCURSAL;

    IF :NEW.TIPO_ENTREGA = 'EMPRESA' AND :NEW.DIRECCION_ENTREGA IS NULL THEN
        SELECT DIRECCION INTO V_DIRECCION FROM CLIENTE_9255 WHERE ID_CLIENTE = :NEW.ID_CLIENTE;
        :NEW.DIRECCION_ENTREGA := V_DIRECCION;
    END IF;

    :NEW.ESTADO   := 'EN_PROCESO';
    :NEW.SUBTOTAL := 0;
    :NEW.IMPUESTO := 0;
    :NEW.TOTAL    := 0;
END;
