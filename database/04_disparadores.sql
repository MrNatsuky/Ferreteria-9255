-- Al crear la factura: asigna serie y numero de la sucursal, y el impuesto,
-- moneda y tipo de cambio del pais (RN-12)
CREATE OR REPLACE TRIGGER TRG_BIR_FACTURA_9255
BEFORE INSERT ON FACTURA_9255
FOR EACH ROW
DECLARE
    V_SUCURSAL_BODEGA NUMBER;
    V_DIRECCION       VARCHAR2(200);
BEGIN
    SELECT S.SERIE_FACTURA, P.PORCENTAJE_IMPUESTO, P.MONEDA_CODIGO, P.TIPO_CAMBIO_QUETZAL
      INTO :NEW.SERIE, :NEW.PORCENTAJE_IMPUESTO, :NEW.MONEDA_CODIGO, :NEW.TIPO_CAMBIO_QUETZAL
      FROM SUCURSAL_9255 S
      JOIN REGION_9255 R ON R.ID_REGION = S.ID_REGION
      JOIN PAIS_9255 P   ON P.ID_PAIS = R.ID_PAIS
     WHERE S.ID_SUCURSAL = :NEW.ID_SUCURSAL;

    SELECT ID_SUCURSAL INTO V_SUCURSAL_BODEGA FROM BODEGA_9255 WHERE ID_BODEGA = :NEW.ID_BODEGA;
    IF V_SUCURSAL_BODEGA <> :NEW.ID_SUCURSAL THEN
        RAISE_APPLICATION_ERROR(-20210, 'La bodega no pertenece a la sucursal de la factura.');
    END IF;

    -- Siguiente numero de factura de la sucursal
    UPDATE SUCURSAL_9255
       SET CORRELATIVO_FACTURA = CORRELATIVO_FACTURA + 1
     WHERE ID_SUCURSAL = :NEW.ID_SUCURSAL;
    SELECT CORRELATIVO_FACTURA INTO :NEW.NUMERO FROM SUCURSAL_9255 WHERE ID_SUCURSAL = :NEW.ID_SUCURSAL;

    -- Si la empresa entrega y no se indico direccion, se usa la del cliente
    IF :NEW.TIPO_ENTREGA = 'EMPRESA' AND :NEW.DIRECCION_ENTREGA IS NULL THEN
        SELECT DIRECCION INTO V_DIRECCION FROM CLIENTE_9255 WHERE ID_CLIENTE = :NEW.ID_CLIENTE;
        :NEW.DIRECCION_ENTREGA := V_DIRECCION;
    END IF;

    :NEW.ESTADO   := 'EN_PROCESO';
    :NEW.SUBTOTAL := 0;
    :NEW.IMPUESTO := 0;
    :NEW.TOTAL    := 0;
END;
/

-- RN-01: una factura EMITIDA no se puede modificar ni anular; se corrige con nota de credito
CREATE OR REPLACE TRIGGER TRG_BUR_FACTURA_9255
BEFORE UPDATE ON FACTURA_9255
FOR EACH ROW
BEGIN
    IF :OLD.ESTADO = 'EMITIDA' THEN
        RAISE_APPLICATION_ERROR(-20211, 'La factura ' || :OLD.SERIE || '-' || :OLD.NUMERO
                                || ' ya fue emitida: no se puede modificar ni anular. Emita una nota de credito.');
    END IF;
    IF :NEW.FECHA_ELIMINACION IS NOT NULL THEN
        RAISE_APPLICATION_ERROR(-20212, 'Las facturas no se pueden eliminar.');
    END IF;
END;
/

-- Antes de agregar un producto: revisa existencia y asigna precio, subtotal y garantia
-- (igual que TRG_BIR_DETALLE_FACTURA de clase)
CREATE OR REPLACE TRIGGER TRG_BIR_DETALLE_FACTURA_9255
BEFORE INSERT ON DETALLE_FACTURA_9255
FOR EACH ROW
DECLARE
    V_ESTADO      VARCHAR2(15);
    V_BODEGA      NUMBER;
    V_TIPO_CAMBIO NUMBER(10,4);
    V_FECHA       DATE;
    V_PRECIO      NUMBER(12,2);
    V_GARANTIA    NUMBER;
    V_EXISTENCIA  NUMBER(12,2);
BEGIN
    SELECT ESTADO, ID_BODEGA, TIPO_CAMBIO_QUETZAL, FECHA_EMISION
      INTO V_ESTADO, V_BODEGA, V_TIPO_CAMBIO, V_FECHA
      FROM FACTURA_9255
     WHERE ID_FACTURA = :NEW.ID_FACTURA;

    IF V_ESTADO <> 'EN_PROCESO' THEN
        RAISE_APPLICATION_ERROR(-20213, 'No se pueden agregar productos a una factura emitida.');
    END IF;

    BEGIN
        SELECT PRECIO_VENTA, MESES_GARANTIA
          INTO V_PRECIO, V_GARANTIA
          FROM PRODUCTO_9255
         WHERE ID_PRODUCTO = :NEW.ID_PRODUCTO;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20214, 'El producto con ID ' || :NEW.ID_PRODUCTO || ' no existe.');
    END;

    V_EXISTENCIA := FN_EXISTENCIA_9255(V_BODEGA, :NEW.ID_PRODUCTO);
    IF V_EXISTENCIA < :NEW.CANTIDAD THEN
        RAISE_APPLICATION_ERROR(-20215, 'NO HAY EXISTENCIA SUFICIENTE PARA EFECTUAR LA VENTA. Disponible: ' || V_EXISTENCIA);
    END IF;

    -- El precio del catalogo esta en quetzales; se convierte a la moneda del pais
    :NEW.PRECIO_UNITARIO := ROUND(V_PRECIO / V_TIPO_CAMBIO, 2);
    :NEW.DESCUENTO       := NVL(:NEW.DESCUENTO, 0);
    :NEW.SUBTOTAL        := ROUND(:NEW.CANTIDAD * :NEW.PRECIO_UNITARIO - :NEW.DESCUENTO, 2);

    IF V_GARANTIA > 0 THEN
        :NEW.FECHA_FIN_GARANTIA := ADD_MONTHS(TRUNC(V_FECHA), V_GARANTIA);
    END IF;
END;
/

-- Despues de agregar un producto: registra la salida de inventario y suma al total
-- de la factura (igual que TRG_AIR_DETALLE_FACTURA de clase)
CREATE OR REPLACE TRIGGER TRG_AIR_DETALLE_FACTURA_9255
AFTER INSERT ON DETALLE_FACTURA_9255
FOR EACH ROW
DECLARE
    V_BODEGA   NUMBER;
    V_EMPLEADO NUMBER;
    V_FECHA    DATE;
    V_SERIE    VARCHAR2(10);
    V_NUMERO   NUMBER;
    V_COSTO    NUMBER(12,2);
BEGIN
    SELECT ID_BODEGA, ID_EMPLEADO, FECHA_EMISION, SERIE, NUMERO
      INTO V_BODEGA, V_EMPLEADO, V_FECHA, V_SERIE, V_NUMERO
      FROM FACTURA_9255
     WHERE ID_FACTURA = :NEW.ID_FACTURA;

    SELECT PRECIO_COSTO INTO V_COSTO FROM PRODUCTO_9255 WHERE ID_PRODUCTO = :NEW.ID_PRODUCTO;

    PRC_REGISTRA_MOV_INVENTARIO_9255('SALIDA_VENTA', V_BODEGA, :NEW.ID_PRODUCTO, :NEW.CANTIDAD, V_COSTO,
                                     V_EMPLEADO, 'FACTURA ' || V_SERIE || '-' || V_NUMERO, V_FECHA);

    UPDATE FACTURA_9255
       SET SUBTOTAL = SUBTOTAL + :NEW.SUBTOTAL,
           IMPUESTO = ROUND((SUBTOTAL + :NEW.SUBTOTAL) * PORCENTAJE_IMPUESTO / 100, 2),
           TOTAL    = (SUBTOTAL + :NEW.SUBTOTAL) + ROUND((SUBTOTAL + :NEW.SUBTOTAL) * PORCENTAJE_IMPUESTO / 100, 2)
     WHERE ID_FACTURA = :NEW.ID_FACTURA;
END;
/

