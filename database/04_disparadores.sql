-- RN-10: control de estados del envio. Al salir a ruta, el vehiculo y el piloto deben
-- estar disponibles y quedan EN_RUTA; al entregar, quedan disponibles de nuevo.
CREATE OR REPLACE TRIGGER TRG_BUR_ENVIO_9255
BEFORE UPDATE OF ESTADO ON ENVIO_9255
FOR EACH ROW
DECLARE
    V_VEHICULO VARCHAR2(15);
    V_PILOTO   VARCHAR2(15);
BEGIN
    IF :OLD.ESTADO = 'PROGRAMADO' AND :NEW.ESTADO = 'EN_RUTA' THEN
        SELECT ESTADO INTO V_VEHICULO FROM VEHICULO_9255 WHERE ID_VEHICULO = :NEW.ID_VEHICULO;
        SELECT ESTADO INTO V_PILOTO   FROM PILOTO_9255   WHERE ID_PILOTO   = :NEW.ID_PILOTO;
        IF V_VEHICULO <> 'DISPONIBLE' THEN
            RAISE_APPLICATION_ERROR(-20280, 'El vehiculo no esta disponible (' || V_VEHICULO || ').');
        END IF;
        IF V_PILOTO <> 'DISPONIBLE' THEN
            RAISE_APPLICATION_ERROR(-20281, 'El piloto ya tiene un envio en ruta.');
        END IF;
        UPDATE VEHICULO_9255 SET ESTADO = 'EN_RUTA' WHERE ID_VEHICULO = :NEW.ID_VEHICULO;
        UPDATE PILOTO_9255   SET ESTADO = 'EN_RUTA' WHERE ID_PILOTO   = :NEW.ID_PILOTO;
        :NEW.FECHA_SALIDA := NVL(:NEW.FECHA_SALIDA, SYSDATE);

    ELSIF :OLD.ESTADO = 'EN_RUTA' AND :NEW.ESTADO = 'ENTREGADO' THEN
        UPDATE VEHICULO_9255 SET ESTADO = 'DISPONIBLE' WHERE ID_VEHICULO = :NEW.ID_VEHICULO;
        UPDATE PILOTO_9255   SET ESTADO = 'DISPONIBLE' WHERE ID_PILOTO   = :NEW.ID_PILOTO;
        :NEW.FECHA_ENTREGA := NVL(:NEW.FECHA_ENTREGA, SYSDATE);

    ELSIF :OLD.ESTADO = 'PROGRAMADO' AND :NEW.ESTADO = 'CANCELADO' THEN
        NULL;

    ELSIF :OLD.ESTADO <> :NEW.ESTADO THEN
        RAISE_APPLICATION_ERROR(-20282, 'No se puede pasar un envio de ' || :OLD.ESTADO || ' a ' || :NEW.ESTADO || '.');
    END IF;
END;
/

