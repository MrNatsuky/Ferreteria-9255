CREATE OR REPLACE TRIGGER TRG_BIR_DETALLE_NOTA_CREDITO_9255
BEFORE INSERT ON DETALLE_NOTA_CREDITO_9255
FOR EACH ROW
DECLARE
    V_ESTADO       VARCHAR2(15);
    V_TIPO         VARCHAR2(15);
    V_FACTURA_NOTA NUMBER;
    V_FACTURA_DET  NUMBER;
    V_VENDIDO      NUMBER(12,2);
    V_SUBTOTAL     NUMBER(12,2);
    V_PORCENTAJE   NUMBER(5,2);
    V_DEVUELTO     NUMBER(12,2);
BEGIN
    SELECT ESTADO, TIPO, ID_FACTURA INTO V_ESTADO, V_TIPO, V_FACTURA_NOTA
      FROM NOTA_CREDITO_9255 WHERE ID_NOTA_CREDITO = :NEW.ID_NOTA_CREDITO;
    IF V_ESTADO <> 'EN_PROCESO' THEN
        RAISE_APPLICATION_ERROR(-20250, 'La nota de credito ya fue emitida.');
    END IF;
    IF V_TIPO <> 'DEVOLUCION' THEN
        RAISE_APPLICATION_ERROR(-20251, 'Solo las notas de credito por devolucion llevan productos.');
    END IF;

    SELECT D.ID_FACTURA, D.CANTIDAD, D.SUBTOTAL, F.PORCENTAJE_IMPUESTO
      INTO V_FACTURA_DET, V_VENDIDO, V_SUBTOTAL, V_PORCENTAJE
      FROM DETALLE_FACTURA_9255 D
      JOIN FACTURA_9255 F ON F.ID_FACTURA = D.ID_FACTURA
     WHERE D.ID_DETALLE_FACTURA = :NEW.ID_DETALLE_FACTURA;
    IF V_FACTURA_DET <> V_FACTURA_NOTA THEN
        RAISE_APPLICATION_ERROR(-20252, 'El producto no pertenece a la factura de la nota de credito.');
    END IF;

    SELECT NVL(SUM(CANTIDAD), 0) INTO V_DEVUELTO
      FROM DETALLE_NOTA_CREDITO_9255 WHERE ID_DETALLE_FACTURA = :NEW.ID_DETALLE_FACTURA;
    IF V_DEVUELTO + :NEW.CANTIDAD > V_VENDIDO THEN
        RAISE_APPLICATION_ERROR(-20253, 'Se intenta devolver mas de lo vendido. Pendiente: ' || (V_VENDIDO - V_DEVUELTO));
    END IF;

    :NEW.MONTO := ROUND(:NEW.CANTIDAD * (V_SUBTOTAL / V_VENDIDO) * (1 + V_PORCENTAJE / 100), 2);
END;
/

