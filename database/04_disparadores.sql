-- RN-09: solo se envian facturas emitidas con entrega a cargo de la empresa;
-- el vehiculo no puede estar en mantenimiento y la licencia del piloto debe estar vigente
CREATE OR REPLACE TRIGGER TRG_BIR_ENVIO_9255
BEFORE INSERT ON ENVIO_9255
FOR EACH ROW
DECLARE
    V_ESTADO_FACTURA  VARCHAR2(15);
    V_ENTREGA         VARCHAR2(10);
    V_ESTADO_VEHICULO VARCHAR2(15);
    V_LICENCIA        DATE;
BEGIN
    SELECT ESTADO, TIPO_ENTREGA, ID_SUCURSAL, DIRECCION_ENTREGA
      INTO V_ESTADO_FACTURA, V_ENTREGA, :NEW.ID_SUCURSAL, :NEW.DIRECCION_ENTREGA
      FROM FACTURA_9255
     WHERE ID_FACTURA = :NEW.ID_FACTURA;

    IF V_ESTADO_FACTURA <> 'EMITIDA' THEN
        RAISE_APPLICATION_ERROR(-20270, 'Solo se programan envios de facturas emitidas.');
    END IF;
    IF V_ENTREGA <> 'EMPRESA' THEN
        RAISE_APPLICATION_ERROR(-20271, 'El cliente transporta su mercaderia: no se programa envio.');
    END IF;

    SELECT ESTADO INTO V_ESTADO_VEHICULO FROM VEHICULO_9255 WHERE ID_VEHICULO = :NEW.ID_VEHICULO;
    IF V_ESTADO_VEHICULO = 'MANTENIMIENTO' THEN
        RAISE_APPLICATION_ERROR(-20272, 'El vehiculo esta en mantenimiento.');
    END IF;

    SELECT FECHA_VENCIMIENTO_LICENCIA INTO V_LICENCIA FROM PILOTO_9255 WHERE ID_PILOTO = :NEW.ID_PILOTO;
    IF V_LICENCIA < TRUNC(:NEW.FECHA_PROGRAMADA) THEN
        RAISE_APPLICATION_ERROR(-20273, 'La licencia del piloto esta vencida.');
    END IF;

    :NEW.ESTADO := 'PROGRAMADO';
END;
/

