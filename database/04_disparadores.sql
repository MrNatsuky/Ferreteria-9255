-- Al insertar guardan quien y cuando creo el registro; al modificar, quien y
-- cuando lo modifico; si se llena FECHA_ELIMINACION, quien lo elimino.
-- Ademas no permiten DELETE: la eliminacion siempre es logica.
-- --------------------------------------------------------------------------------

CREATE OR REPLACE TRIGGER TRG_AUD_PAIS_9255
BEFORE INSERT OR UPDATE OR DELETE ON PAIS_9255
FOR EACH ROW
BEGIN
    IF INSERTING THEN
        :NEW.CREADO_POR := FN_USUARIO_9255;
        :NEW.FECHA_CREACION := SYSDATE;
    ELSIF UPDATING THEN
        :NEW.MODIFICADO_POR := FN_USUARIO_9255;
        :NEW.FECHA_MODIFICACION := SYSDATE;
        IF :NEW.FECHA_ELIMINACION IS NOT NULL AND :OLD.FECHA_ELIMINACION IS NULL THEN
            :NEW.ELIMINADO_POR := FN_USUARIO_9255;
        END IF;
    ELSIF DELETING THEN
        RAISE_APPLICATION_ERROR(-20000, 'No se permite borrar registros de PAIS_9255. Use la eliminacion logica.');
    END IF;
END;
