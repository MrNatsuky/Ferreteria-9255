CREATE OR REPLACE TRIGGER TRG_AIR_MOVIMIENTO_INVENTARIO_9255
AFTER INSERT ON MOVIMIENTO_INVENTARIO_9255
FOR EACH ROW
DECLARE
    V_OPERACION  CHAR(1);
    V_EXISTENCIA NUMBER(12,2);
BEGIN
    SELECT OPERACION INTO V_OPERACION
      FROM TIPO_MOVIMIENTO_9255
     WHERE ID_TIPO_MOVIMIENTO = :NEW.ID_TIPO_MOVIMIENTO;

    V_EXISTENCIA := FN_EXISTENCIA_9255(:NEW.ID_SUCURSAL, :NEW.ID_PRODUCTO);

    IF V_OPERACION = '-' THEN
        IF V_EXISTENCIA < :NEW.CANTIDAD THEN
            RAISE_APPLICATION_ERROR(-20201, 'No hay existencia suficiente del producto ' || :NEW.ID_PRODUCTO
                                    || ' en la sucursal ' || :NEW.ID_SUCURSAL || '. Disponible: ' || V_EXISTENCIA);
        END IF;
        UPDATE INVENTARIO_9255
           SET EXISTENCIA = EXISTENCIA - :NEW.CANTIDAD,
               FECHA_ULTIMO_MOVIMIENTO = :NEW.FECHA_MOVIMIENTO
         WHERE ID_SUCURSAL = :NEW.ID_SUCURSAL
           AND ID_PRODUCTO = :NEW.ID_PRODUCTO;
    ELSE
        UPDATE INVENTARIO_9255
           SET EXISTENCIA = EXISTENCIA + :NEW.CANTIDAD,
               FECHA_ULTIMO_MOVIMIENTO = :NEW.FECHA_MOVIMIENTO
         WHERE ID_SUCURSAL = :NEW.ID_SUCURSAL
           AND ID_PRODUCTO = :NEW.ID_PRODUCTO;
        IF SQL%ROWCOUNT = 0 THEN
            INSERT INTO INVENTARIO_9255 (ID_SUCURSAL, ID_PRODUCTO, EXISTENCIA, FECHA_ULTIMO_MOVIMIENTO)
            VALUES (:NEW.ID_SUCURSAL, :NEW.ID_PRODUCTO, :NEW.CANTIDAD, :NEW.FECHA_MOVIMIENTO);
        END IF;
    END IF;
END;
/

