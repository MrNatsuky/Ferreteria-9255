-- RN-02: la nota debe ser sobre una factura emitida y la suma de las notas no puede
-- pasar del total de la factura. Asigna la serie (NC + serie de la sucursal) y el numero.
CREATE OR REPLACE TRIGGER TRG_BIR_NOTA_CREDITO_9255
BEFORE INSERT ON NOTA_CREDITO_9255
FOR EACH ROW
DECLARE
    V_ESTADO     VARCHAR2(15);
    V_TOTAL      NUMBER(12,2);
    V_SUCURSAL   NUMBER;
    V_ACREDITADO NUMBER(12,2);
BEGIN
    SELECT ESTADO, TOTAL, ID_SUCURSAL
      INTO V_ESTADO, V_TOTAL, V_SUCURSAL
      FROM FACTURA_9255
     WHERE ID_FACTURA = :NEW.ID_FACTURA;

    IF V_ESTADO <> 'EMITIDA' THEN
        RAISE_APPLICATION_ERROR(-20240, 'Solo se emiten notas de credito sobre facturas emitidas.');
    END IF;

    SELECT NVL(SUM(MONTO), 0) INTO V_ACREDITADO FROM NOTA_CREDITO_9255 WHERE ID_FACTURA = :NEW.ID_FACTURA;
    IF V_ACREDITADO + :NEW.MONTO > V_TOTAL THEN
        RAISE_APPLICATION_ERROR(-20241, 'La nota de credito supera lo que queda por acreditar de la factura ('
                                || (V_TOTAL - V_ACREDITADO) || ').');
    END IF;

    UPDATE SUCURSAL_9255
       SET CORRELATIVO_NOTA_CREDITO = CORRELATIVO_NOTA_CREDITO + 1
     WHERE ID_SUCURSAL = V_SUCURSAL;
    SELECT 'NC' || SERIE_FACTURA, CORRELATIVO_NOTA_CREDITO
      INTO :NEW.SERIE, :NEW.NUMERO
      FROM SUCURSAL_9255
     WHERE ID_SUCURSAL = V_SUCURSAL;
END;
/

-- Si la factura es al credito, la nota de credito rebaja lo que debe el cliente
CREATE OR REPLACE TRIGGER TRG_AIR_NOTA_CREDITO_9255
AFTER INSERT ON NOTA_CREDITO_9255
FOR EACH ROW
DECLARE
    V_SALDO NUMBER(12,2);
BEGIN
    SELECT SALDO INTO V_SALDO FROM CUENTA_POR_COBRAR_9255 WHERE ID_FACTURA = :NEW.ID_FACTURA;
    IF :NEW.MONTO >= V_SALDO THEN
        UPDATE CUENTA_POR_COBRAR_9255 SET SALDO = 0, ESTADO = 'PAGADA' WHERE ID_FACTURA = :NEW.ID_FACTURA;
    ELSE
        UPDATE CUENTA_POR_COBRAR_9255 SET SALDO = SALDO - :NEW.MONTO WHERE ID_FACTURA = :NEW.ID_FACTURA;
    END IF;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        NULL;  -- la factura es al contado: no tiene cuenta por cobrar
END;
/

