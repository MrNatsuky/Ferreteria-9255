-- Antes de registrar un producto devuelto: debe ser de la misma factura, no pasar de
-- lo vendido, y calcula el monto a devolver (con impuesto)
CREATE OR REPLACE TRIGGER TRG_BIR_DETALLE_DEVOLUCION_9255
BEFORE INSERT ON DETALLE_DEVOLUCION_9255
FOR EACH ROW
DECLARE
    V_ESTADO       VARCHAR2(15);
    V_FACTURA_DEV  NUMBER;
    V_FACTURA_DET  NUMBER;
    V_VENDIDO      NUMBER(12,2);
    V_SUBTOTAL     NUMBER(12,2);
    V_PORCENTAJE   NUMBER(5,2);
    V_DEVUELTO     NUMBER(12,2);
BEGIN
    SELECT ESTADO, ID_FACTURA INTO V_ESTADO, V_FACTURA_DEV
      FROM DEVOLUCION_9255 WHERE ID_DEVOLUCION = :NEW.ID_DEVOLUCION;
    IF V_ESTADO <> 'PENDIENTE' THEN
        RAISE_APPLICATION_ERROR(-20250, 'La devolucion ya fue aprobada.');
    END IF;

    SELECT D.ID_FACTURA, D.CANTIDAD, D.SUBTOTAL, F.PORCENTAJE_IMPUESTO
      INTO V_FACTURA_DET, V_VENDIDO, V_SUBTOTAL, V_PORCENTAJE
      FROM DETALLE_FACTURA_9255 D
      JOIN FACTURA_9255 F ON F.ID_FACTURA = D.ID_FACTURA
     WHERE D.ID_DETALLE_FACTURA = :NEW.ID_DETALLE_FACTURA;
    IF V_FACTURA_DET <> V_FACTURA_DEV THEN
        RAISE_APPLICATION_ERROR(-20251, 'El producto no pertenece a la factura de la devolucion.');
    END IF;

    SELECT NVL(SUM(CANTIDAD), 0) INTO V_DEVUELTO
      FROM DETALLE_DEVOLUCION_9255 WHERE ID_DETALLE_FACTURA = :NEW.ID_DETALLE_FACTURA;
    IF V_DEVUELTO + :NEW.CANTIDAD > V_VENDIDO THEN
        RAISE_APPLICATION_ERROR(-20252, 'Se intenta devolver mas de lo vendido. Pendiente: ' || (V_VENDIDO - V_DEVUELTO));
    END IF;

    :NEW.MONTO := ROUND(:NEW.CANTIDAD * (V_SUBTOTAL / V_VENDIDO) * (1 + V_PORCENTAJE / 100), 2);
END;
/

-- Despues de registrar un producto devuelto: si esta en buen estado vuelve a la bodega,
-- y su monto se suma al total de la devolucion
CREATE OR REPLACE TRIGGER TRG_AIR_DETALLE_DEVOLUCION_9255
AFTER INSERT ON DETALLE_DEVOLUCION_9255
FOR EACH ROW
DECLARE
    V_BODEGA   NUMBER;
    V_PRODUCTO NUMBER;
    V_EMPLEADO NUMBER;
    V_FECHA    DATE;
    V_COSTO    NUMBER(12,2);
BEGIN
    IF :NEW.ESTADO_PRODUCTO = 'BUENO' THEN
        SELECT F.ID_BODEGA, D.ID_PRODUCTO, P.PRECIO_COSTO
          INTO V_BODEGA, V_PRODUCTO, V_COSTO
          FROM DETALLE_FACTURA_9255 D
          JOIN FACTURA_9255 F  ON F.ID_FACTURA = D.ID_FACTURA
          JOIN PRODUCTO_9255 P ON P.ID_PRODUCTO = D.ID_PRODUCTO
         WHERE D.ID_DETALLE_FACTURA = :NEW.ID_DETALLE_FACTURA;

        SELECT ID_EMPLEADO, FECHA_DEVOLUCION INTO V_EMPLEADO, V_FECHA
          FROM DEVOLUCION_9255 WHERE ID_DEVOLUCION = :NEW.ID_DEVOLUCION;

        PRC_REGISTRA_MOV_INVENTARIO_9255('INGRESO_DEVOLUCION', V_BODEGA, V_PRODUCTO, :NEW.CANTIDAD, V_COSTO,
                                         V_EMPLEADO, 'DEVOLUCION ' || :NEW.ID_DEVOLUCION, V_FECHA);
    END IF;

    UPDATE DEVOLUCION_9255
       SET MONTO = MONTO + :NEW.MONTO
     WHERE ID_DEVOLUCION = :NEW.ID_DEVOLUCION;
END;
/

-- RN-11: el reclamo de garantia solo procede dentro del tiempo de garantia
CREATE OR REPLACE TRIGGER TRG_BIR_RECLAMO_GARANTIA_9255
BEFORE INSERT ON RECLAMO_GARANTIA_9255
FOR EACH ROW
DECLARE
    V_FIN DATE;
BEGIN
    SELECT FECHA_FIN_GARANTIA INTO V_FIN
