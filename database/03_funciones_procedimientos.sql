CREATE OR REPLACE FUNCTION FN_USUARIO_9255 RETURN VARCHAR2 IS
BEGIN
    RETURN NVL(SYS_CONTEXT('USERENV', 'CLIENT_IDENTIFIER'), USER);
END;
/

CREATE OR REPLACE FUNCTION FN_EXISTENCIA_9255 (P_ID_SUCURSAL IN NUMBER, P_ID_PRODUCTO IN NUMBER) RETURN NUMBER IS
    V_EXISTENCIA NUMBER(12,2);
BEGIN
    SELECT EXISTENCIA
      INTO V_EXISTENCIA
      FROM INVENTARIO_9255
     WHERE ID_SUCURSAL = P_ID_SUCURSAL
       AND ID_PRODUCTO = P_ID_PRODUCTO;
    RETURN V_EXISTENCIA;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN 0;
END;
/

CREATE OR REPLACE FUNCTION FN_SALDO_CLIENTE_9255 (P_ID_CLIENTE IN NUMBER) RETURN NUMBER IS
    V_SALDO NUMBER(12,2);
BEGIN
    SELECT NVL(SUM(SALDO), 0)
      INTO V_SALDO
      FROM CUENTA_POR_COBRAR_9255
     WHERE ID_CLIENTE = P_ID_CLIENTE
       AND ESTADO = 'PENDIENTE';
    RETURN V_SALDO;
END;
/

CREATE OR REPLACE PROCEDURE PRC_REGISTRA_MOV_INVENTARIO_9255 (
    P_CODIGO_TIPO IN VARCHAR2,
    P_ID_SUCURSAL IN NUMBER,
    P_ID_PRODUCTO IN NUMBER,
    P_CANTIDAD    IN NUMBER,
    P_COSTO       IN NUMBER,
    P_ID_EMPLEADO IN NUMBER,
    P_REFERENCIA  IN VARCHAR2,
    P_FECHA       IN DATE DEFAULT SYSDATE
) IS
    V_ID_TIPO NUMBER;
BEGIN
    BEGIN
        SELECT ID_TIPO_MOVIMIENTO
          INTO V_ID_TIPO
          FROM TIPO_MOVIMIENTO_9255
         WHERE CODIGO = P_CODIGO_TIPO;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20100, 'No existe el tipo de movimiento ' || P_CODIGO_TIPO);
    END;

    INSERT INTO MOVIMIENTO_INVENTARIO_9255
        (ID_TIPO_MOVIMIENTO, ID_SUCURSAL, ID_PRODUCTO, CANTIDAD, COSTO_UNITARIO, ID_EMPLEADO,
         FECHA_MOVIMIENTO, DOCUMENTO_REFERENCIA)
    VALUES
        (V_ID_TIPO, P_ID_SUCURSAL, P_ID_PRODUCTO, P_CANTIDAD, P_COSTO, P_ID_EMPLEADO,
         P_FECHA, P_REFERENCIA);
END;
/

CREATE OR REPLACE PROCEDURE PRC_TRASLADAR_PRODUCTO_9255 (
    P_ID_SUCURSAL_ORIGEN  IN NUMBER,
    P_ID_SUCURSAL_DESTINO IN NUMBER,
    P_ID_PRODUCTO         IN NUMBER,
    P_CANTIDAD            IN NUMBER,
    P_ID_EMPLEADO         IN NUMBER,
    P_FECHA               IN DATE DEFAULT SYSDATE
) IS
    V_COSTO NUMBER(12,2);
BEGIN
    IF P_ID_SUCURSAL_ORIGEN = P_ID_SUCURSAL_DESTINO THEN
        RAISE_APPLICATION_ERROR(-20101, 'La sucursal de origen y la de destino deben ser distintas.');
    END IF;

    SELECT PRECIO_COSTO INTO V_COSTO FROM PRODUCTO_9255 WHERE ID_PRODUCTO = P_ID_PRODUCTO;

    PRC_REGISTRA_MOV_INVENTARIO_9255('SALIDA_TRASLADO', P_ID_SUCURSAL_ORIGEN, P_ID_PRODUCTO, P_CANTIDAD,
                                     V_COSTO, P_ID_EMPLEADO, 'TRASLADO A SUCURSAL ' || P_ID_SUCURSAL_DESTINO, P_FECHA);
    PRC_REGISTRA_MOV_INVENTARIO_9255('INGRESO_TRASLADO', P_ID_SUCURSAL_DESTINO, P_ID_PRODUCTO, P_CANTIDAD,
                                     V_COSTO, P_ID_EMPLEADO, 'TRASLADO DE SUCURSAL ' || P_ID_SUCURSAL_ORIGEN, P_FECHA);
END;
/

CREATE OR REPLACE PROCEDURE PRC_CERRAR_FACTURA_9255 (P_ID_FACTURA IN NUMBER) IS
    V_ESTADO       VARCHAR2(15);
    V_TIPO_VENTA   VARCHAR2(10);
    V_TOTAL        NUMBER(12,2);
    V_ID_CLIENTE   NUMBER;
    V_FECHA        DATE;
    V_PRODUCTOS    NUMBER;
    V_PAGADO       NUMBER(12,2);
    V_LIMITE       NUMBER(12,2);
    V_DIAS         NUMBER;
BEGIN
    SELECT ESTADO, TIPO_VENTA, TOTAL, ID_CLIENTE, FECHA_EMISION
      INTO V_ESTADO, V_TIPO_VENTA, V_TOTAL, V_ID_CLIENTE, V_FECHA
      FROM FACTURA_9255
     WHERE ID_FACTURA = P_ID_FACTURA;

    IF V_ESTADO <> 'EN_PROCESO' THEN
        RAISE_APPLICATION_ERROR(-20110, 'La factura ya fue emitida.');
    END IF;

    SELECT COUNT(*) INTO V_PRODUCTOS FROM DETALLE_FACTURA_9255 WHERE ID_FACTURA = P_ID_FACTURA;
    IF V_PRODUCTOS = 0 THEN
        RAISE_APPLICATION_ERROR(-20111, 'La factura no tiene productos.');
    END IF;

    IF V_TIPO_VENTA = 'CONTADO' THEN
        SELECT NVL(SUM(MONTO), 0) INTO V_PAGADO FROM PAGO_FACTURA_9255 WHERE ID_FACTURA = P_ID_FACTURA;
        IF V_PAGADO <> V_TOTAL THEN
            RAISE_APPLICATION_ERROR(-20112, 'Los pagos (' || V_PAGADO || ') no cuadran con el total de la factura (' || V_TOTAL || ').');
        END IF;
    ELSE
        SELECT LIMITE_CREDITO, DIAS_CREDITO INTO V_LIMITE, V_DIAS FROM CLIENTE_9255 WHERE ID_CLIENTE = V_ID_CLIENTE;
        IF V_LIMITE = 0 THEN
            RAISE_APPLICATION_ERROR(-20113, 'El cliente no tiene credito autorizado.');
        END IF;
        IF FN_SALDO_CLIENTE_9255(V_ID_CLIENTE) + V_TOTAL > V_LIMITE THEN
            RAISE_APPLICATION_ERROR(-20114, 'La venta supera el limite de credito del cliente. Disponible: '
                                    || (V_LIMITE - FN_SALDO_CLIENTE_9255(V_ID_CLIENTE)));
        END IF;
        INSERT INTO CUENTA_POR_COBRAR_9255
            (ID_FACTURA, ID_CLIENTE, MONTO_TOTAL, SALDO, FECHA_EMISION, FECHA_VENCIMIENTO)
        VALUES
            (P_ID_FACTURA, V_ID_CLIENTE, V_TOTAL, V_TOTAL, TRUNC(V_FECHA), TRUNC(V_FECHA) + V_DIAS);
    END IF;

    UPDATE FACTURA_9255 SET ESTADO = 'EMITIDA' WHERE ID_FACTURA = P_ID_FACTURA;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20115, 'No existe la factura ' || P_ID_FACTURA);
END;
/

CREATE OR REPLACE PROCEDURE PRC_CERRAR_NOTA_CREDITO_9255 (P_ID_NOTA_CREDITO IN NUMBER) IS
    V_ESTADO     VARCHAR2(15);
    V_ID_FACTURA NUMBER;
    V_MONTO      NUMBER(12,2);
    V_TOTAL      NUMBER(12,2);
    V_ACREDITADO NUMBER(12,2);
    V_SALDO      NUMBER(12,2);
BEGIN
    SELECT ESTADO, ID_FACTURA, MONTO
      INTO V_ESTADO, V_ID_FACTURA, V_MONTO
      FROM NOTA_CREDITO_9255
     WHERE ID_NOTA_CREDITO = P_ID_NOTA_CREDITO;

    IF V_ESTADO <> 'EN_PROCESO' THEN
        RAISE_APPLICATION_ERROR(-20120, 'La nota de credito ya fue emitida.');
    END IF;
    IF V_MONTO <= 0 THEN
        RAISE_APPLICATION_ERROR(-20121, 'La nota de credito no tiene monto.');
    END IF;

    SELECT TOTAL INTO V_TOTAL FROM FACTURA_9255 WHERE ID_FACTURA = V_ID_FACTURA;
    SELECT NVL(SUM(MONTO), 0) INTO V_ACREDITADO
      FROM NOTA_CREDITO_9255
     WHERE ID_FACTURA = V_ID_FACTURA
       AND ESTADO = 'EMITIDA';
    IF V_ACREDITADO + V_MONTO > V_TOTAL THEN
        RAISE_APPLICATION_ERROR(-20122, 'La nota de credito supera lo que queda por acreditar de la factura ('
                                || (V_TOTAL - V_ACREDITADO) || ').');
    END IF;

    BEGIN
        SELECT SALDO INTO V_SALDO FROM CUENTA_POR_COBRAR_9255 WHERE ID_FACTURA = V_ID_FACTURA;
        IF V_MONTO >= V_SALDO THEN
            UPDATE CUENTA_POR_COBRAR_9255 SET SALDO = 0, ESTADO = 'PAGADA' WHERE ID_FACTURA = V_ID_FACTURA;
        ELSE
            UPDATE CUENTA_POR_COBRAR_9255 SET SALDO = SALDO - V_MONTO WHERE ID_FACTURA = V_ID_FACTURA;
        END IF;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            NULL;
    END;

    UPDATE NOTA_CREDITO_9255 SET ESTADO = 'EMITIDA' WHERE ID_NOTA_CREDITO = P_ID_NOTA_CREDITO;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20123, 'No existe la nota de credito ' || P_ID_NOTA_CREDITO);
END;
/

CREATE OR REPLACE PROCEDURE PRC_RECIBIR_COMPRA_9255 (
    P_ID_COMPRA   IN NUMBER,
    P_ID_EMPLEADO IN NUMBER,
    P_FECHA       IN DATE DEFAULT SYSDATE
) IS
    V_ESTADO      VARCHAR2(15);
    V_SUCURSAL    NUMBER;
    V_TIPO_PAGO   VARCHAR2(10);
    V_TOTAL       NUMBER(12,2);
    V_TIPO_CAMBIO NUMBER(10,4);
    V_DIAS        NUMBER;
BEGIN
    SELECT C.ESTADO, C.ID_SUCURSAL, C.TIPO_PAGO, C.TOTAL, C.TIPO_CAMBIO_QUETZAL, P.DIAS_CREDITO
      INTO V_ESTADO, V_SUCURSAL, V_TIPO_PAGO, V_TOTAL, V_TIPO_CAMBIO, V_DIAS
      FROM COMPRA_9255 C
      JOIN PROVEEDOR_9255 P ON P.ID_PROVEEDOR = C.ID_PROVEEDOR
     WHERE C.ID_COMPRA = P_ID_COMPRA;

    IF V_ESTADO <> 'PENDIENTE' THEN
        RAISE_APPLICATION_ERROR(-20130, 'Solo se pueden recibir compras en estado PENDIENTE.');
    END IF;

    FOR D IN (SELECT ID_PRODUCTO, CANTIDAD, COSTO_UNITARIO
                FROM DETALLE_COMPRA_9255
               WHERE ID_COMPRA = P_ID_COMPRA) LOOP
        PRC_REGISTRA_MOV_INVENTARIO_9255('INGRESO_COMPRA', V_SUCURSAL, D.ID_PRODUCTO, D.CANTIDAD,
                                         ROUND(D.COSTO_UNITARIO * V_TIPO_CAMBIO, 2), P_ID_EMPLEADO,
                                         'COMPRA ' || P_ID_COMPRA, P_FECHA);
    END LOOP;

    UPDATE COMPRA_9255
       SET ESTADO = 'RECIBIDA',
           FECHA_RECEPCION = P_FECHA
     WHERE ID_COMPRA = P_ID_COMPRA;

    IF V_TIPO_PAGO = 'CREDITO' THEN
        INSERT INTO CUENTA_POR_PAGAR_9255 (ID_COMPRA, MONTO_TOTAL, SALDO, FECHA_EMISION, FECHA_VENCIMIENTO)
        VALUES (P_ID_COMPRA, V_TOTAL, V_TOTAL, TRUNC(P_FECHA), TRUNC(P_FECHA) + V_DIAS);
    END IF;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20131, 'No existe la compra ' || P_ID_COMPRA);
END;
/
