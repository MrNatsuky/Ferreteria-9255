CREATE OR REPLACE TRIGGER TRG_BIR_DETALLE_FACTURA_9255
BEFORE INSERT ON DETALLE_FACTURA_9255
FOR EACH ROW
DECLARE
    V_ESTADO      VARCHAR2(15);
    V_SUCURSAL    NUMBER;
    V_TIPO_CAMBIO NUMBER(10,4);
    V_FECHA       DATE;
    V_PRECIO      NUMBER(12,2);
    V_GARANTIA    NUMBER;
    V_EXISTENCIA  NUMBER(12,2);
BEGIN
    SELECT ESTADO, ID_SUCURSAL, TIPO_CAMBIO_QUETZAL, FECHA_EMISION
      INTO V_ESTADO, V_SUCURSAL, V_TIPO_CAMBIO, V_FECHA
      FROM FACTURA_9255
     WHERE ID_FACTURA = :NEW.ID_FACTURA;

    IF V_ESTADO <> 'EN_PROCESO' THEN
        RAISE_APPLICATION_ERROR(-20001, 'No se pueden agregar productos a una factura emitida.');
    END IF;

    BEGIN
        SELECT PRECIO_VENTA, MESES_GARANTIA
          INTO V_PRECIO, V_GARANTIA
          FROM PRODUCTO_9255
         WHERE ID_PRODUCTO = :NEW.ID_PRODUCTO;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20002, 'El producto con ID ' || :NEW.ID_PRODUCTO || ' no existe.');
    END;

    V_EXISTENCIA := PAQ_INVENTARIO_9255.FN_EXISTENCIA_9255(V_SUCURSAL, :NEW.ID_PRODUCTO);

    IF V_EXISTENCIA < :NEW.CANTIDAD THEN
        RAISE_APPLICATION_ERROR(-20003, 'NO HAY EXISTENCIA SUFICIENTE PARA EFECTUAR LA VENTA. Disponible: ' || V_EXISTENCIA);
    END IF;

    :NEW.PRECIO_UNITARIO := ROUND(V_PRECIO / V_TIPO_CAMBIO, 2);
    :NEW.DESCUENTO       := NVL(:NEW.DESCUENTO, 0);
    :NEW.SUBTOTAL        := ROUND(:NEW.CANTIDAD * :NEW.PRECIO_UNITARIO - :NEW.DESCUENTO, 2);

    IF V_GARANTIA > 0 THEN
        :NEW.FECHA_FIN_GARANTIA := ADD_MONTHS(TRUNC(V_FECHA), V_GARANTIA);
    END IF;
END;
/

CREATE OR REPLACE TRIGGER TRG_AIR_DETALLE_FACTURA_9255
AFTER INSERT ON DETALLE_FACTURA_9255
FOR EACH ROW
DECLARE
    V_SUCURSAL NUMBER;
    V_EMPLEADO NUMBER;
    V_FECHA    DATE;
    V_SERIE    VARCHAR2(10);
    V_NUMERO   NUMBER;
    V_COSTO    NUMBER(12,2);
BEGIN
    SELECT ID_SUCURSAL, ID_EMPLEADO, FECHA_EMISION, SERIE, NUMERO
      INTO V_SUCURSAL, V_EMPLEADO, V_FECHA, V_SERIE, V_NUMERO
      FROM FACTURA_9255
     WHERE ID_FACTURA = :NEW.ID_FACTURA;

    SELECT PRECIO_COSTO INTO V_COSTO FROM PRODUCTO_9255 WHERE ID_PRODUCTO = :NEW.ID_PRODUCTO;

    PAQ_INVENTARIO_9255.PRC_REGISTRA_MOV_INVENTARIO_9255('SALIDA_VENTA', V_SUCURSAL, :NEW.ID_PRODUCTO, :NEW.CANTIDAD, V_COSTO,
                                                         V_EMPLEADO, 'FACTURA ' || V_SERIE || '-' || V_NUMERO, V_FECHA, :NEW.CREADO_POR);

    UPDATE FACTURA_9255
       SET SUBTOTAL       = SUBTOTAL + :NEW.SUBTOTAL,
           IMPUESTO       = ROUND((SUBTOTAL + :NEW.SUBTOTAL) * PORCENTAJE_IMPUESTO / 100, 2),
           TOTAL          = (SUBTOTAL + :NEW.SUBTOTAL) + ROUND((SUBTOTAL + :NEW.SUBTOTAL) * PORCENTAJE_IMPUESTO / 100, 2),
           MODIFICADO_POR = :NEW.CREADO_POR
     WHERE ID_FACTURA = :NEW.ID_FACTURA;
END;
/

CREATE OR REPLACE TRIGGER TRG_AIR_MOVIMIENTO_INVENTARIO_9255
AFTER INSERT ON MOVIMIENTO_INVENTARIO_9255
FOR EACH ROW
DECLARE
    V_OPERACION  CHAR(1);
    V_EXISTENCIA NUMBER(12,2);
BEGIN
    SELECT OPERACION INTO V_OPERACION
      FROM TIPO_MOVIMIENTO_9255
     WHERE ID_TIPO_MOVIMIENTO = :NEW.ID_TIPO_MOVIMIENTO;

    BEGIN
        SELECT EXISTENCIA
          INTO V_EXISTENCIA
          FROM INVENTARIO_9255
         WHERE ID_SUCURSAL = :NEW.ID_SUCURSAL
           AND ID_PRODUCTO = :NEW.ID_PRODUCTO;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            V_EXISTENCIA := NULL;
    END;

    IF V_OPERACION = '-' THEN
        IF NVL(V_EXISTENCIA, 0) < :NEW.CANTIDAD THEN
            RAISE_APPLICATION_ERROR(-20004, 'No hay existencia suficiente del producto ' || :NEW.ID_PRODUCTO
                                    || ' en la sucursal ' || :NEW.ID_SUCURSAL || '. Disponible: ' || NVL(V_EXISTENCIA, 0));
        END IF;
        UPDATE INVENTARIO_9255
           SET EXISTENCIA = EXISTENCIA - :NEW.CANTIDAD,
               FECHA_ULTIMO_MOVIMIENTO = :NEW.FECHA_MOVIMIENTO,
               MODIFICADO_POR = :NEW.CREADO_POR
         WHERE ID_SUCURSAL = :NEW.ID_SUCURSAL
           AND ID_PRODUCTO = :NEW.ID_PRODUCTO;
    ELSIF V_EXISTENCIA IS NULL THEN
        INSERT INTO INVENTARIO_9255 (ID_SUCURSAL, ID_PRODUCTO, EXISTENCIA, FECHA_ULTIMO_MOVIMIENTO, CREADO_POR)
        VALUES (:NEW.ID_SUCURSAL, :NEW.ID_PRODUCTO, :NEW.CANTIDAD, :NEW.FECHA_MOVIMIENTO, :NEW.CREADO_POR);
    ELSE
        UPDATE INVENTARIO_9255
           SET EXISTENCIA = EXISTENCIA + :NEW.CANTIDAD,
               FECHA_ULTIMO_MOVIMIENTO = :NEW.FECHA_MOVIMIENTO,
               MODIFICADO_POR = :NEW.CREADO_POR
         WHERE ID_SUCURSAL = :NEW.ID_SUCURSAL
           AND ID_PRODUCTO = :NEW.ID_PRODUCTO;
    END IF;
END;
/

