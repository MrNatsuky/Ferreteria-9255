DECLARE
    V_FECHA      DATE;
    V_SUCURSAL   NUMBER;
    V_PAIS       NUMBER;
    V_CLIENTE    NUMBER;
    V_VENDEDOR   NUMBER;
    V_TIPO_VENTA VARCHAR2(10);
    V_ENTREGA    VARCHAR2(10);
    V_DIRECCION  VARCHAR2(200);
    V_SERIE      VARCHAR2(10);
    V_NUMERO     NUMBER;
    V_PORCENTAJE NUMBER(5,2);
    V_MONEDA     CHAR(3);
    V_TC         NUMBER(10,4);
    V_ID_FACTURA NUMBER;
    V_LINEAS     NUMBER;
    V_PRODUCTO   NUMBER;
    V_MINIMA     NUMBER;
    V_CANTIDAD   NUMBER;
    V_EXISTENCIA NUMBER;
    V_TOTAL      NUMBER(12,2);
    V_LIMITE     NUMBER(12,2);
    V_DIAS       NUMBER;
    V_SALDO      NUMBER(12,2);
    V_FORMA      NUMBER;
    V_REFERENCIA VARCHAR2(40);
BEGIN
    DBMS_RANDOM.SEED(9255);
    FOR I IN 1..40 LOOP
        V_SUCURSAL := TRUNC(DBMS_RANDOM.VALUE(1, 7));
        V_PAIS     := CEIL(V_SUCURSAL / 2);
        IF V_SUCURSAL = 1 THEN
            V_VENDEDOR := 7 + TRUNC(DBMS_RANDOM.VALUE(0, 2));
        ELSE
            V_VENDEDOR := V_SUCURSAL + 7;
        END IF;
        V_CLIENTE := (V_PAIS - 1) * 4 + TRUNC(DBMS_RANDOM.VALUE(1, 5));

        SELECT LIMITE_CREDITO, DIAS_CREDITO, DIRECCION INTO V_LIMITE, V_DIAS, V_DIRECCION
          FROM CLIENTE_9255 WHERE ID_CLIENTE = V_CLIENTE;

        IF V_LIMITE > 0 AND DBMS_RANDOM.VALUE < 0.5 THEN
            V_TIPO_VENTA := 'CREDITO';
        ELSE
            V_TIPO_VENTA := 'CONTADO';
        END IF;

        IF MOD(V_SUCURSAL, 2) = 1 AND V_DIRECCION IS NOT NULL AND DBMS_RANDOM.VALUE < 0.4 THEN
            V_ENTREGA := 'EMPRESA';
        ELSE
            V_ENTREGA := 'CLIENTE';
            V_DIRECCION := NULL;
        END IF;

        V_FECHA := DATE '2026-01-07' + (I - 1) * 7 + TRUNC(DBMS_RANDOM.VALUE(8, 18)) / 24;

        SELECT SU.SERIE_FACTURA, P.PORCENTAJE_IMPUESTO, P.MONEDA_CODIGO, P.TIPO_CAMBIO_QUETZAL
          INTO V_SERIE, V_PORCENTAJE, V_MONEDA, V_TC
          FROM SUCURSAL_9255 SU
         INNER JOIN REGION_9255 R ON R.ID_REGION = SU.ID_REGION
         INNER JOIN PAIS_9255 P   ON P.ID_PAIS = R.ID_PAIS
         WHERE SU.ID_SUCURSAL = V_SUCURSAL;

        UPDATE SUCURSAL_9255 SET CORRELATIVO_FACTURA = CORRELATIVO_FACTURA + 1 WHERE ID_SUCURSAL = V_SUCURSAL;
        SELECT CORRELATIVO_FACTURA INTO V_NUMERO FROM SUCURSAL_9255 WHERE ID_SUCURSAL = V_SUCURSAL;

        INSERT INTO FACTURA_9255 (ID_SUCURSAL, ID_CLIENTE, ID_EMPLEADO, SERIE, NUMERO, FECHA_EMISION, TIPO_VENTA,
                                  TIPO_ENTREGA, DIRECCION_ENTREGA, PORCENTAJE_IMPUESTO, MONEDA_CODIGO, TIPO_CAMBIO_QUETZAL)
        VALUES (V_SUCURSAL, V_CLIENTE, V_VENDEDOR, V_SERIE, V_NUMERO, V_FECHA, V_TIPO_VENTA,
                V_ENTREGA, V_DIRECCION, V_PORCENTAJE, V_MONEDA, V_TC)
        RETURNING ID_FACTURA INTO V_ID_FACTURA;

        V_LINEAS := TRUNC(DBMS_RANDOM.VALUE(1, 4));
        FOR L IN 1..V_LINEAS LOOP
            V_PRODUCTO := TRUNC(10 * POWER(DBMS_RANDOM.VALUE, 1.5)) + 1;
            SELECT EXISTENCIA_MINIMA INTO V_MINIMA FROM PRODUCTO_9255 WHERE ID_PRODUCTO = V_PRODUCTO;
            IF V_MINIMA >= 100 THEN
                V_CANTIDAD := 10 * TRUNC(DBMS_RANDOM.VALUE(1, 6));
            ELSIF V_MINIMA >= 30 THEN
                V_CANTIDAD := TRUNC(DBMS_RANDOM.VALUE(2, 11));
            ELSE
                V_CANTIDAD := TRUNC(DBMS_RANDOM.VALUE(1, 4));
            END IF;

            V_EXISTENCIA := PAQ_INVENTARIO_9255.FN_EXISTENCIA_9255(V_SUCURSAL, V_PRODUCTO);
            IF V_EXISTENCIA >= V_CANTIDAD THEN
                INSERT INTO DETALLE_FACTURA_9255 (ID_FACTURA, ID_PRODUCTO, CANTIDAD)
                VALUES (V_ID_FACTURA, V_PRODUCTO, V_CANTIDAD);
            END IF;
        END LOOP;

        SELECT COUNT(*) INTO V_LINEAS FROM DETALLE_FACTURA_9255 WHERE ID_FACTURA = V_ID_FACTURA;
        IF V_LINEAS = 0 THEN
            INSERT INTO DETALLE_FACTURA_9255 (ID_FACTURA, ID_PRODUCTO, CANTIDAD) VALUES (V_ID_FACTURA, 6, 10);
        END IF;

        SELECT TOTAL INTO V_TOTAL FROM FACTURA_9255 WHERE ID_FACTURA = V_ID_FACTURA;

        IF V_TIPO_VENTA = 'CREDITO' THEN
            V_SALDO := FN_SALDO_CLIENTE_9255(V_CLIENTE);
            IF V_SALDO + V_TOTAL > V_LIMITE THEN
                V_TIPO_VENTA := 'CONTADO';
                UPDATE FACTURA_9255 SET TIPO_VENTA = 'CONTADO' WHERE ID_FACTURA = V_ID_FACTURA;
            END IF;
        END IF;

        IF V_TIPO_VENTA = 'CONTADO' THEN
            V_FORMA := MOD(I, 4) + 1;
            IF V_FORMA = 1 THEN
                V_REFERENCIA := NULL;
            ELSE
                V_REFERENCIA := TO_CHAR(10000000 + I * 7919);
            END IF;
            INSERT INTO PAGO_FACTURA_9255 (ID_FACTURA, ID_FORMA_PAGO, FECHA_PAGO, MONTO, NUMERO_REFERENCIA)
            VALUES (V_ID_FACTURA, V_FORMA, V_FECHA, V_TOTAL, V_REFERENCIA);
        ELSE
            INSERT INTO CUENTA_POR_COBRAR_9255 (ID_FACTURA, ID_CLIENTE, MONTO_TOTAL, SALDO, FECHA_EMISION, FECHA_VENCIMIENTO)
            VALUES (V_ID_FACTURA, V_CLIENTE, V_TOTAL, V_TOTAL, TRUNC(V_FECHA), TRUNC(V_FECHA) + V_DIAS);
        END IF;

        UPDATE FACTURA_9255 SET ESTADO = 'EMITIDA' WHERE ID_FACTURA = V_ID_FACTURA;
    END LOOP;
    COMMIT;
    DBMS_OUTPUT.PUT_LINE('Facturas emitidas.');
END;
