CREATE OR REPLACE PACKAGE BODY PAQ_INVENTARIO_9255 AS

    FUNCTION FN_EXISTENCIA_9255 (P_ID_SUCURSAL IN NUMBER, P_ID_PRODUCTO IN NUMBER) RETURN NUMBER IS
        V_EXISTENCIA NUMBER(12,2);
    BEGIN
        SELECT EXISTENCIA
          INTO V_EXISTENCIA
          FROM INVENTARIO_9255
         WHERE ID_SUCURSAL = P_ID_SUCURSAL
           AND ID_PRODUCTO = P_ID_PRODUCTO;
        RETURN V_EXISTENCIA;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RETURN 0;
    END;

    PROCEDURE PRC_REGISTRA_MOV_INVENTARIO_9255 (
        P_CODIGO_TIPO IN VARCHAR2,
        P_ID_SUCURSAL IN NUMBER,
        P_ID_PRODUCTO IN NUMBER,
        P_CANTIDAD    IN NUMBER,
        P_COSTO       IN NUMBER,
        P_ID_EMPLEADO IN NUMBER,
        P_REFERENCIA  IN VARCHAR2,
        P_FECHA       IN DATE,
        P_USUARIO     IN VARCHAR2
    ) IS
        V_ID_TIPO NUMBER;
    BEGIN
        SELECT ID_TIPO_MOVIMIENTO
          INTO V_ID_TIPO
          FROM TIPO_MOVIMIENTO_9255
         WHERE CODIGO = P_CODIGO_TIPO;

        INSERT INTO MOVIMIENTO_INVENTARIO_9255
            (ID_TIPO_MOVIMIENTO, ID_SUCURSAL, ID_PRODUCTO, CANTIDAD, COSTO_UNITARIO, ID_EMPLEADO,
             FECHA_MOVIMIENTO, DOCUMENTO_REFERENCIA, CREADO_POR)
        VALUES
            (V_ID_TIPO, P_ID_SUCURSAL, P_ID_PRODUCTO, P_CANTIDAD, P_COSTO, P_ID_EMPLEADO,
             P_FECHA, P_REFERENCIA, NVL(P_USUARIO, USER));
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20100, 'No existe el tipo de movimiento ' || P_CODIGO_TIPO);
    END;

    PROCEDURE PRC_TRASLADAR_PRODUCTO_9255 (
        P_ID_SUCURSAL_ORIGEN  IN NUMBER,
        P_ID_SUCURSAL_DESTINO IN NUMBER,
        P_ID_PRODUCTO         IN NUMBER,
        P_CANTIDAD            IN NUMBER,
        P_ID_EMPLEADO         IN NUMBER,
        P_FECHA               IN DATE,
        P_USUARIO             IN VARCHAR2
    ) IS
        V_COSTO NUMBER(12,2);
    BEGIN
        IF P_ID_SUCURSAL_ORIGEN = P_ID_SUCURSAL_DESTINO THEN
            RAISE_APPLICATION_ERROR(-20103, 'La sucursal de origen y la de destino deben ser distintas.');
        END IF;

        SELECT PRECIO_COSTO INTO V_COSTO FROM PRODUCTO_9255 WHERE ID_PRODUCTO = P_ID_PRODUCTO;

        PRC_REGISTRA_MOV_INVENTARIO_9255('SALIDA_TRASLADO', P_ID_SUCURSAL_ORIGEN, P_ID_PRODUCTO, P_CANTIDAD, V_COSTO,
                                         P_ID_EMPLEADO, 'TRASLADO A SUCURSAL ' || P_ID_SUCURSAL_DESTINO, P_FECHA, P_USUARIO);
        PRC_REGISTRA_MOV_INVENTARIO_9255('INGRESO_TRASLADO', P_ID_SUCURSAL_DESTINO, P_ID_PRODUCTO, P_CANTIDAD, V_COSTO,
                                         P_ID_EMPLEADO, 'TRASLADO DE SUCURSAL ' || P_ID_SUCURSAL_ORIGEN, P_FECHA, P_USUARIO);
    END;

END PAQ_INVENTARIO_9255;
