CREATE OR REPLACE VIEW VW_CLIENTES_POR_REGION_9255 AS
SELECT P.NOMBRE                                  AS PAIS,
       R.NOMBRE                                  AS REGION,
       C.ID_CLIENTE,
       C.NOMBRE                                  AS CLIENTE,
       COUNT(F.ID_FACTURA)                       AS CANTIDAD_FACTURAS,
       SUM(ROUND(F.TOTAL * F.TIPO_CAMBIO_QUETZAL, 2)) AS TOTAL_QUETZALES
  FROM FACTURA_9255 F
 INNER JOIN CLIENTE_9255 C  ON C.ID_CLIENTE = F.ID_CLIENTE
 INNER JOIN SUCURSAL_9255 S ON S.ID_SUCURSAL = F.ID_SUCURSAL
 INNER JOIN REGION_9255 R   ON R.ID_REGION = S.ID_REGION
 INNER JOIN PAIS_9255 P     ON P.ID_PAIS = R.ID_PAIS
 WHERE F.ESTADO = 'EMITIDA'
 GROUP BY P.NOMBRE, R.NOMBRE, C.ID_CLIENTE, C.NOMBRE;

CREATE OR REPLACE VIEW VW_VENDEDORES_POR_REGION_9255 AS
SELECT P.NOMBRE                                  AS PAIS,
       R.NOMBRE                                  AS REGION,
       S.NOMBRE                                  AS SUCURSAL,
       E.ID_EMPLEADO,
       E.NOMBRES || ' ' || E.APELLIDOS           AS VENDEDOR,
       COUNT(F.ID_FACTURA)                       AS CANTIDAD_FACTURAS,
       SUM(ROUND(F.TOTAL * F.TIPO_CAMBIO_QUETZAL, 2)) AS TOTAL_QUETZALES
  FROM FACTURA_9255 F
 INNER JOIN EMPLEADO_9255 E ON E.ID_EMPLEADO = F.ID_EMPLEADO
 INNER JOIN SUCURSAL_9255 S ON S.ID_SUCURSAL = F.ID_SUCURSAL
 INNER JOIN REGION_9255 R   ON R.ID_REGION = S.ID_REGION
 INNER JOIN PAIS_9255 P     ON P.ID_PAIS = R.ID_PAIS
 WHERE F.ESTADO = 'EMITIDA'
 GROUP BY P.NOMBRE, R.NOMBRE, S.NOMBRE, E.ID_EMPLEADO, E.NOMBRES, E.APELLIDOS;

CREATE OR REPLACE VIEW VW_PRODUCTOS_VENDIDOS_9255 AS
SELECT PR.ID_PRODUCTO,
       PR.CODIGO,
       PR.NOMBRE                                 AS PRODUCTO,
       CA.NOMBRE                                 AS CATEGORIA,
       NVL(SUM(CASE WHEN F.ID_FACTURA IS NOT NULL THEN D.CANTIDAD END), 0) AS UNIDADES_VENDIDAS,
       NVL(SUM(ROUND(D.SUBTOTAL * F.TIPO_CAMBIO_QUETZAL, 2)), 0) AS TOTAL_QUETZALES
  FROM PRODUCTO_9255 PR
 INNER JOIN CATEGORIA_9255 CA ON CA.ID_CATEGORIA = PR.ID_CATEGORIA
  LEFT JOIN DETALLE_FACTURA_9255 D ON D.ID_PRODUCTO = PR.ID_PRODUCTO
  LEFT JOIN FACTURA_9255 F ON F.ID_FACTURA = D.ID_FACTURA AND F.ESTADO = 'EMITIDA'
 GROUP BY PR.ID_PRODUCTO, PR.CODIGO, PR.NOMBRE, CA.NOMBRE;

CREATE OR REPLACE VIEW VW_ENVIOS_POR_SUCURSAL_9255 AS
SELECT P.NOMBRE                                  AS PAIS,
       S.NOMBRE                                  AS SUCURSAL,
       E.NOMBRES || ' ' || E.APELLIDOS           AS RESPONSABLE,
       COUNT(EN.ID_ENVIO)                        AS TOTAL_ENVIOS,
       SUM(CASE WHEN EN.ESTADO = 'ENTREGADO' THEN 1 ELSE 0 END) AS ENTREGADOS,
       SUM(CASE WHEN EN.ESTADO = 'PROGRAMADO' OR EN.ESTADO = 'EN_RUTA' THEN 1 ELSE 0 END) AS PENDIENTES
  FROM ENVIO_9255 EN
 INNER JOIN SUCURSAL_9255 S ON S.ID_SUCURSAL = EN.ID_SUCURSAL
 INNER JOIN REGION_9255 R   ON R.ID_REGION = S.ID_REGION
 INNER JOIN PAIS_9255 P     ON P.ID_PAIS = R.ID_PAIS
 INNER JOIN EMPLEADO_9255 E ON E.ID_EMPLEADO = EN.ID_EMPLEADO_RESPONSABLE
 WHERE EN.ESTADO <> 'CANCELADO'
 GROUP BY P.NOMBRE, S.NOMBRE, E.NOMBRES, E.APELLIDOS;
